 * ★ **U-2（2026-10-11）起本表没有活条目**（`SLOT_SCENES` 已空 ⇒ [presetScopeNotice] 恒
 * `null`）。**为什么保留**：它是"将来又出现单侧槽位时"的名字表 —— 那时往 `SLOT_SCENES`
 * 加条、这里加名即可，不必重新找回四个入口的文案口径（且 `PresetScopeTest` 的
