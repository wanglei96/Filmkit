 *
 * ⚠ `[5..10]` 用**"胶片曲线"**而不是工程术语"趾肩 latitude"（P-5 复核裁决：普通用户不认
 * "趾肩"）—— 它是 filmic 曲线两端的 latitude，UI 上没有滑杆，用户能感知的是"整条胶片曲线
 * 的形态"。
