package com.filmkit.app.ui

/**
 * 内置预设：只保留「标准」= 无风格化中性基线（基准色彩科学：log 域 + 胶片曲线骨架，
 * 全部参数中性）。
 *
 * 预设机制定位（2026-09-20 拍板）：预设 = 用户自建（LUT + 参数调节保存）。
 * ★ 2026-10-11 更新（P-2b/P-2c）：随包分发的**内置胶片预设**已重新引入（`BuiltinPresets` +
 * `assets/presets/builtin.json`），但它走的是**另一条数据通道**（只读、不进 prefs）——
 * 本文件仍然只有「标准」这一条基线，`names` / `byIndex` 那套"按索引取预设"的死代码已删除
 *（P-2c 裁决 ④；列表与选中态现在一律按 **id** 走 `EditorPreset`）。
 *
 * 教训（X300 事故）：DoubleArray 默认全 0，而对比度 0 = 灰板、串扰矩阵 0 = 信号清零、
 * 白平衡 0 = 全黑——必须从 neutral() 基线出发再覆盖。
 */
object CameraPresets {

    /** 参数数组长度 = C++ `FilmParams.h::kCount`（阶段 0 引擎插槽起 99）。
     *  Kotlin 侧**只此一处**定义长度：本文件的 `neutral()` 与
     *  `CameraController.setFilmParams` 的长度兜底都读它 ⇒ 少一个漂移点
     *（v0.10.196 的启动崩溃就是"两处长度不一致"造成的）。 */
    const val COUNT = 99

    /**
     * `[98] engine_slot` 的**默认档位** = `1`（sigmoid）—— 用户 2026-10-14 拍板
     * （`docs/rec2020-heif-design.md` §1b P2 行："默认拍照效果全面好于 filmic；filmic 后期可能想删，
     * 本期先留"）。
     *
     * 与 C++ `core/engine/src/film/FilmParams.h` 的 `float engine_slot = 1.0f;` 是**同一件事的两侧**
     * （那个文件是本仓库"默认值"的单一真源；JVM 单测读不到 C++ 常量，故两侧各写一次、由
     * `CameraPresetsTest` + `Stage3EngineSlotPresetAuditTest` 钉住）。
     *
     * 为什么要一个常量而不是到处写 `1.0`：**"缺 `[98]` 时按哪一档解释"必须全仓一个答案** ——
     * 读取侧有两类缺省形态（UI 读预设稀疏 slots / 引擎下发前读长度不足的历史快照），
     * 它们与 C++ 的 `fromDoubles` 缺槽行为（保持结构体默认）必须一致，否则会出现
     * "渲染走引擎 N、UI 按引擎 M 隐藏参数"的假读数（卡 C 2026-10-14 报过同型缺陷）。
     */
    const val DEFAULT_ENGINE_SLOT = 1

    private fun put3(a: DoubleArray, i: Int, v0: Double, v1: Double, v2: Double) {
        a[i] = v0; a[i + 1] = v1; a[i + 2] = v2
    }

    /** 中性基线：所有参数处于"无效果"的正确默认值。 */
    // ⚠ 长度必须与 C++ `core/engine/src/film/FilmParams.h::kCount` **逐位一致**。
    // v0.10.196 教训：加 [59] color_smooth 时只改了 C++ 的 kCount（59→60），
    // 这里仍是 59 ⇒ CameraController 写 filmParams[59] 直接
    // ArrayIndexOutOfBoundsException ⇒ **装包后应用启动即崩**（真机 2026-10-08）。
    // 以后加参数槽位：**四处一起改**（本行 + kCount + fromDoubles 防呆
    // + setFilmParams 长度兜底）。
    private fun neutral(): DoubleArray = DoubleArray(COUNT).apply {
        put3(this, 1, 1.0, 1.0, 1.0)     // 白平衡增益
        this[4] = 1.0                     // 对比度
        // [5..10] E4-1 起语义 = **filmic latitude**（per-channel 0..1），不再是
        // "软肩/toe 强度（0 = 关）"。⚠️ 必须显式写 **0.01**：latitude 语义下
        // `0` = 过渡区紧贴中灰 = **极端 S 曲线**（不是"无效果"）。0.01 = darktable
        // 默认，也正是引擎当前的实际行为（`FrameRenderer.h` 的 computeFilmicSpline
        // 声明 `latitude = 0.01f`，`FrameRenderer.cpp:11555` 调用只传 3 个实参 ⇒
        // 恒取该默认）。shader 当前零引用（E4-4 才接线）⇒ 此处改动不影响成片。
        put3(this, 5, 0.01, 0.01, 0.01)  // shoulder(latitude) R/G/B
        put3(this, 8, 0.01, 0.01, 0.01)  // toe(latitude) R/G/B
        // 染料串扰 = 单位阵
        put3(this, 11, 1.0, 0.0, 0.0)
        put3(this, 14, 0.0, 1.0, 0.0)
        put3(this, 17, 0.0, 0.0, 1.0)
        put3(this, 20, 1.0, 1.0, 1.0)     // 分区饱和度
        // [26][27] 颗粒（E4-1 起语义 = darktable grain 的 `strength` / `scale`=ISO）。
        // ⚠️ ADR-10 硬约束：[26] **必须保持 0.0 = 整段旁路** —— 给非零会让所有用户
        // 现有拍摄立刻带上颗粒（成片外观回归）。颗粒只由预设/编辑器显式开启。
        // [27] = 400：新语义（越大越粗，20..6400）下的标定起点（≈9px，见设计文档
        // §3.1.4）；amount = 0 时不可达，但显式下发修掉了"`neutral()` 未设置 vs
        // C++ 兜底"的不一致（勘察 R9 / ADR-5）。
        this[26] = 0.0
        this[27] = 400.0
        // 28 = 基准影调强度：1.0 = 开（黑位 + 中灰锚定 S + 高光 rolloff，
        // 非风格化；治"发灰"）。0 = 恒等/旧行为。
        this[28] = 1.0
        // 29 = 高光重建强度：1.0 = 开（CCM 前用未饱和通道外推饱和通道）。
        this[29] = 1.0
        // 30 = 过曝提示阈值（显示域）：0.95 ≈ 242/255，0 = 关；仅预览生效。
        this[30] = 0.95
        // 31..33 = 色彩外观层（M3 P1）：强度 / 饱和增益 / 色度 S 端点。
        // v0.6.14 曾启用（1.5×）去补 C* 缺口，**v0.6.15 回退到中性**：真机复拍发现
        // "严重偏色"——离线分离证明外观层把画面**原有**的暖偏同比放大（白墙 b* +1.63
        // → +2.31、全图 b* +1.49 → +2.56），而 baseTone 的影调修复对色偏**零影响**。
        // 基础引擎的第一要务是"不引入偏差"：饱和增益这类"乘性放大"会把白平衡的
        // 残余误差一起放大，所以先回中性。C* 缺口（3.1 vs libraw 5.6）另议 ——
        // libraw 的 C* 只是它自己的偏好，不等于"正确"，不该盲目对齐。
        this[31] = 1.0
        this[32] = 1.0
        // v0.6.19：色度 S 曲线端点 1.0 → 1.25（真机实测 C* 比厂商同场景低 23%：
        // 4.61 vs 5.96）。只放大"已经浓的色"（|cc| > 0.25），**不动近中性色** ——
        // 所以不会重演 v0.6.14「全局饱和 ×1.5 把白平衡残余误差同比放大」那次偏色。
        // v0.6.22：判据由"绝对线性色度"改为**亮度相对** rel=max|cc|/luma（见 FrameRenderer）。
        // v0.6.23：1.25 → 1.35，与引擎 knee 1.0→0.4 配套。真机三场景 + DNG 对照显示
        //   缺口在**低饱和段**（rel 0.15–0.25 只有参照的 0.59，而 rel 0.7–1.2 段已到 1.22），
        //   故要"低饱和补得多、高饱和补得少"：新剖面 rel0.15→+9%、0.2→+14%、0.3→+23%、
        //   0.5→+20%、1.2→+8%；近中性仅 +0.3~3.6%（远低于 v0.6.14 的 +50%）。
        // v0.7.7：1.35 → **1.0（恒等）**。这一层是旧链"寡淡"的补偿（v0.5.42 诊断：
        // 色度比参照低），实测数据（用户 A/B，同场景）：开=彩色 C* 18.17 / 天空 19.98，
        // 关=14.42 / 15.18，而 PhotonCamera 参照只有 12.21–13.32 —— **关掉后仍偏高**，
        // 说明 filmic 链下"寡淡"的前提已不存在（PC 也没有这一层）。
        // 1.0 时 `1 + (chroma-1)*sk` 恒等于 1，即 S 曲线恒等（不是"倒扣"）。
        // v0.7.9：设置页「色彩外观层」开关已删除（恒等层只控制空操作）；31..33 槽位
        // 保留（FilmParams 契约不移位），引擎 shader 里的 look 层保留但恒等短路。
        this[33] = 1.0
        // 34 = 3D LUT 混合强度（M4）：1.0 = 全量。LUT 资产本身走独立 JNI 上传 3D 纹理，
        // 这里只带强度；未选 LUT 时引擎按 uLutOn = 0 旁路。
        this[34] = 1.0
        // 35 = 自适应影调（v0.7.3 起语义 = **filmic 的黑白点是否自动标定**）：
        // 1.0 = 开（按场景分位算 black/white relative exposure，EV，相对 18.45% 中灰），
        // 0 = 关（固定 darktable 默认 −7.65/+4.56，曲线不随场景变）。
        // ⚠️ v0.7.3 之前的"按场景中位亮度算曝光增益"（kTarget 中位锚定）**已整体废除** ——
        // 它把"曝光"这一维抹掉了（压 EV / 降 AE 都会被 gain 补偿回来）。
        // 设置页开关写 prefs("auto_black_ev")，CameraController 覆盖此值。
        // v0.10.19：三版真机证伪后**默认关**（固定曲线 = PC 行为；HR 阈值已与
        // 曲线解耦不受影响）。
        this[35] = 0.0
        // 36 = 局部色调映射（M4-7）：0 = 关（A/B 通路），>0 = 暗部线性提亮比例。
        // 全局曲线在"边缘高光 + 中央暗部"的高 DR 场景里两难（保高光则中央暗、
        // 提中央则高光爆 —— 离线实测中位锚定会让 6.6%–13% 像素过曝）；局部手段只让
        // 暗区吃到提亮、亮区强度归零，故高光不动、黑位乘性保持。
        // 0.6 ≈ 暗部线性 ×1.6（经 S 曲线放大后显示域约 +55%）。标定旋钮。
        // v0.6.28：0.6 → 0.4。真机反馈"画面有亮斑"—— 0.6 在"大面积白墙 + 暗桌面"
        // 的场景里让 27% 画面满额提亮 60%、另一半几乎不提亮，提亮量空间分布过陡。
        // v0.6.31：0.4 → 0.5，补偿自适应影调新增的高光约束（逆光场景 gain 从 4.0
        // 收到 2.0，暗部少提亮 1EV）—— 局部提亮只碰暗区，是补这一档的正确位置。
        // v0.6.33：0.5 → 0.6 → **0.25**。真机反馈"暗部提亮太多、室内过亮且噪声爆炸"。
        // 回看 roadmap：这一项立项时定的强度就是 **≤0.2–0.3**（须保住全局对比与黑位），
        // 我为了补自适应影调砍掉的增益一路推到 0.6 = **越界 2 倍**。提亮是噪声的乘性
        // 放大器（暗部 ×1.6），这也是"噪声爆炸"的直接来源。
        // 补偿增益的责任归还给 updateAutoGain（其上限已单列），局部层只做温和的暗部
        // 补偿，不再兼任全局曝光。
        // v0.12.30：0（旁路）。M4-7 局部色调映射的设置开关**已移除**，但三处默认值
        // 还留着 0.25 ⇒ 等于**强制开启且用户关不掉**。它与 PC 的差异是实打实的：
        // PC 的 ShadowsHighlightsParams 默认 (0,0)，我们这层是暗部线性提亮 25%（0.32EV）。
        this[36] = 0.0
        // 37/38 = filmic 黑白点（v0.7.6，单位 = 相对中灰 18.45% 的 EV）：
        // −7.65/+4.56 是 darktable 默认值，也是 PhotonCamera 的固化值（两边一致，有出处）。
        // 用户可在设置页自由调整（PC 的做法）；auto_tone 开时**黑点**改由场景分位自动。
        this[37] = -7.65
        this[38] = 4.56
        // 39 = 轻度锐化（v0.9.6）：luma USM，kFsOut 内高光滚降后、OETF 前的线性
        // 显示域（管线顺序与用户定稿一致）。乘法式相对增益，保色度坐标。
        // 为什么不在 OETF 后（PC 的 sharpen 在 sRGB 域）：sRGB 斜率暗部 >1，
        // 同一 USM 放大暗部噪声。0.5 = 标定旋钮，0 = 关（A/B 通路）；
        // 设置页开关写 prefs("sharpen")，CameraController 覆盖此值。
        this[39] = 0.5
        // 40 = filmic 之后的 gamut 收尾（v0.10.13 引入；v0.10.14 曾预删 min/desaturate
        // 两步，**v0.10.17 起恢复完整五步**（用户铁律：先 100% 原版跑通→真机→数据评估），
        // 本注释按 v0.10.22 如实更新）：色度 min + 色相锁定 + Y clamp + desaturate(0)
        // + Yrg 检查 + 解析 clip chroma。min 的暗部灰化是原版行为在本链语境的副作用
        // （PC/darktable 同样带着它），根源在亮度结构、正解在 EV/曝光语义（v0.10.22）。
        // 默认开；0 = A/B 通路。设置页开关写 prefs("gamut")。
        this[40] = 1.0
        // 41 = darktable filmic 高光重建（v0.10.15）：à trous 小波重建部分通道
        // 裁剪的高光（治过曝边缘品红残留），线性 RGB 域、filmic 前。原生算法
        // 完整实现（mask/inpaint/小波/RGB+ratios 两轮），参数 = darktable 默认。
        // 默认**关**（v0.10.162：PC 路子无此模块，本模块与 [45] hr_raw 职责重复）；
        // 1 = 开。设置页开关写 prefs("hr_wavelet")，CameraController.applyHrWaveletPref
        // 是决定下发值的那一层（它总能覆盖这里的预设值）。
        this[41] = 0.0
        // 42 = 白点高光感知（v0.10.27，auto_tone 开时生效）：对数域场景统计 +
        // P99.9 驱动白点上探（≤+1.5EV、物理钳制不变）+ darktable contrast 参数
        // 按 power 前后比补偿中间调回退。治"高光太白压不住"（统计 clamp 使 P99
        // 对强光源失明 → 白点恒钉 2.438 下限 → 肩部挤压 → 高光平顶白墙）。
        // 默认开；0 = A/B 通路（v0.10.18 行为）。设置页开关写 prefs("white_hl")。
        this[42] = 1.0
        // 45 = RAW 域高光重建（v0.10.115，darktable highlights "inpaint opposed"）：
        // 去马赛克**前**对线性 mosaic 的被裁剪通道做对立通道外推（3×3 photosite）+
        // 全图色度校正。补 41 号 hr_wavelet 够不到的一环 —— 后者在 film 域修影调，
        // 恢复不了 RAW 饱和时丢掉的通道信息（2026-10-03 真机：曝光给足使饱和像素
        // 6×，壶身玻璃反光带留彩色伪影）。默认开；0 = A/B 通路。
        // 设置页开关写 prefs("hr_raw")。
        this[45] = 1.0
        // 46 = RCD 色差段回归 RawTherapee 原版（v0.10.117）：1 = 原版行为
        //（对角梯度三项 + **无限幅**，边缘感知靠梯度反比加权）；0 = 旧行为
        //（梯度两项 + clamp 到 4 对角色差范围，实测会把红色扩散进白瓷/过曝区）。
        // 默认 1；0 = A/B 通路。设置页开关写 prefs("rcd_cdfix")。
        this[46] = 1.0
        // 47 = 逆光边缘紫边抑制（v0.10.134）：RawTherapee Defringe 同形态
        //（Lab 域局部基线偏离检测 + a 通道色相门 + 低偏离邻居加权替换，L 零损失）。
        // 基准样片紫边 ↓63%、红物体色度 +1%。默认 1；0 = A/B 通路。
        // 设置页开关写 prefs("defringe")。
        this[47] = 1.0
        // 48 = 伪彩感知色度降噪强度（档 A，v0.10.165）：0 = 关（A/B 通路），
        // >0 = σc 放大倍率（scEff = sc·(1 + moire·[48])，封顶 4·sc）。
        // 默认 2.0 = 离线标定值（详见 core/engine/src/film/FilmParams.h 与本槽注释）。
        // ⚠️ 本槽长度是**硬契约**：`CameraPresets.COUNT`（本文件顶部唯一维护点），数组越界会直接崩。
        this[48] = 2.0
        // 49 = 高光重建算法（v0.10.169 引入，v0.12.4 转正为**算法选择**）：
        // 1 = **自创档**（G 三级池化比 + allSat 三通道同步改写）= 0.12.3 及以前的行为；
        // 0 = **darktable 原版档**（`hlreconstruct/opposed.c` 口径：`MAX(inval, refavg)`
        //     + 加性 chrominance 补偿，**只抬不压**）。
        // v0.12.4 改默认为 0 的依据（一手源码 + 真机量化）：自创 allSat 按参考比**替换**
        // 三通道、并用**满阱 luma** 当亮度锚 ⇒ 把 sat-fix 救回的真值（可达 4.0）压回满阱
        // (≈1.27)，并把高光核色度抹平（真机 164553：亮核 chroma 2.17% vs 紧邻外圈
