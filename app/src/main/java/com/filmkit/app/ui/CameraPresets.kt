package com.filmkit.app.ui

/**
 * 内置预设：只保留「标准」= 无风格化中性基线（基准色彩科学：log 域 + 胶片曲线骨架，
 * 全部参数中性）。
 *
 * 预设机制定位（2026-09-20 拍板）：预设 = 用户自建（LUT + 参数调节保存），内置风格化
 * 预设（负片/黑白）无意义已删除。
 *
 * 教训（X300 事故）：DoubleArray 默认全 0，而对比度 0 = 灰板、串扰矩阵 0 = 信号清零、
 * 白平衡 0 = 全黑——必须从 neutral() 基线出发再覆盖。
 */
object CameraPresets {

    val names = listOf("标准")

    fun byIndex(i: Int): DoubleArray = standard()

    private fun put3(a: DoubleArray, i: Int, v0: Double, v1: Double, v2: Double) {
        a[i] = v0; a[i + 1] = v1; a[i + 2] = v2
    }

    /** 中性基线：所有参数处于"无效果"的正确默认值。 */
    private fun neutral(): DoubleArray = DoubleArray(37).apply {
        put3(this, 1, 1.0, 1.0, 1.0)     // 白平衡增益
        this[4] = 1.0                     // 对比度
        // 染料串扰 = 单位阵
        put3(this, 11, 1.0, 0.0, 0.0)
        put3(this, 14, 0.0, 1.0, 0.0)
        put3(this, 17, 0.0, 0.0, 1.0)
        put3(this, 20, 1.0, 1.0, 1.0)     // 分区饱和度
        // 28 = 基准影调强度：1.0 = 开（黑位 + 中灰锚定 S + 高光 rolloff，
        // 非风格化；治"发灰"）。0 = 恒等/旧行为。
        this[28] = 1.0
        // 29 = 高光重建强度：1.0 = 开（CCM 前用未饱和通道外推饱和通道）。
        this[29] = 1.0
        // 30 = 过曝提示阈值（显示域）：0.95 ≈ 242/255，0 = 关；仅预览生效。
        this[30] = 0.95
        // 31..33 = 色彩外观层（M3 P1）：强度 / 饱和增益 / 色度 S 端点。
        // v0.6.14 曾启用（1.5×）去补 C* 缺口，**v0.6.15 回退到中性**：真机复拍发现
        // "严重偏色"——离线分离证明外观层把画面**原有**的暖偏同比放大（白墙 b* +1.63
        // → +2.31、全图 b* +1.49 → +2.56），而 baseTone 的影调修复对色偏**零影响**。
        // 基础引擎的第一要务是"不引入偏差"：饱和增益这类"乘性放大"会把白平衡的
        // 残余误差一起放大，所以先回中性。C* 缺口（3.1 vs libraw 5.6）另议 ——
        // libraw 的 C* 只是它自己的偏好，不等于"正确"，不该盲目对齐。
        this[31] = 1.0
        this[32] = 1.0
        // v0.6.19：色度 S 曲线端点 1.0 → 1.25（真机实测 C* 比厂商同场景低 23%：
        // 4.61 vs 5.96）。只放大"已经浓的色"（|cc| > 0.25），**不动近中性色** ——
        // 所以不会重演 v0.6.14「全局饱和 ×1.5 把白平衡残余误差同比放大」那次偏色。
        // v0.6.22：判据由"绝对线性色度"改为**亮度相对** rel=max|cc|/luma（见 FrameRenderer）。
        // v0.6.23：1.25 → 1.35，与引擎 knee 1.0→0.4 配套。真机三场景 + DNG 对照显示
        //   缺口在**低饱和段**（rel 0.15–0.25 只有参照 0.59，而 rel 0.7–1.2 已 1.22），
        //   故要"低饱和补得多、高饱和补得少"：新剖面 rel0.15→+9%、0.2→+14%、0.3→+23%、
        //   0.5→+20%、1.2→+8%；近中性仅 +0.3~3.6%（远低于 v0.6.14 的 +50%）。
        this[33] = 1.35
        // 34 = 3D LUT 混合强度（M4）：1.0 = 全量。LUT 资产本身走独立 JNI 上传 3D 纹理，
        // 这里只带强度；未选 LUT 时引擎按 uLutOn = 0 旁路。
        this[34] = 1.0
        // 35 = 自适应影调（M4-6）：1.0 = 开（按场景中位亮度自动算曝光增益，默认），
        // 0 = 关（退回固定 exp2(0.35)）。v0.6.26 判据改为**中位锚定**：与 PhotonCamera
        // 同机位对照发现差距在中间调（P50 79 vs 131，高光只差 1.1×），归一到 baseTone
        // 的中间调不动点后 P50 落到 128（离线 6 张样片 P50 120–131、gain 1.56–2.59、
        // clip 全 0%）。设置页开关写 prefs("auto_tone")，CameraController 覆盖此值。
        this[35] = 1.0
        // 36 = 局部色调映射（M4-7）：0 = 关（A/B 通路），>0 = 暗部线性提亮比例。
        // 全局曲线在"边缘高光 + 中央暗部"的高 DR 场景里两难（保高光则中央暗、
        // 提中央则高光爆 —— 离线实测中位锚定会让 6.6%–13% 像素过曝）；局部手段只让
        // 暗区吃到提亮、亮区强度归零，故高光不动、黑位乘性保持。
        // 0.6 ≈ 暗部线性 ×1.6（经 S 曲线放大后显示域约 +55%）。标定旋钮。
        // v0.6.28：0.6 → 0.4。真机反馈"画面有亮斑"—— 0.6 在"大面积白墙 + 暗桌面"
        // 的场景里让 27% 画面满额提亮 60%、另一半几乎不提亮，提亮量空间分布过陡。
        // v0.6.31：0.4 → 0.5，补偿自适应影调新增的高光约束（逆光场景 gain 从 4.0
        // 收到 2.0，暗部少提亮 1EV）—— 局部提亮只碰暗区，是补这一档的正确位置。
        // v0.6.33：0.5 → 0.6 → **0.25**。真机反馈"暗部提亮太多、室内过亮且噪声爆炸"。
        // 回看 roadmap：这一项立项时定的强度就是 **≤0.2–0.3**（须保住全局对比与黑位），
        // 我为了补自适应影调砍掉的增益一路推到 0.6 = **越界 2 倍**。提亮是噪声的乘性
        // 放大器（暗部 ×1.6），这也是"噪声爆炸"的直接来源。
        // 补偿增益的责任归还给 updateAutoGain（其上限已单列），局部层只做温和的暗部
        // 补偿，不再兼任全局曝光。
        this[36] = 0.25
    }

    /** 标准 = 原片：全中性（含饱和度 1.0），偏差全部归零便于色彩问题归因 */
    fun standard(): DoubleArray = neutral()
}
