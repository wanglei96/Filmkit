        this[50] = 1.0
        // 51..53 = 强边缘色度门 v2（v0.10.174）：
        // PC `esd3d2.glsl:78-82` = `chromaDiff *= max(|Δx|,|Δy|)` +
        // `sigZ = max(sigY, min(chromaNoise·MOIRE, 0.2))`，且色度权重 w2 = 1−d²/(d²+σ)
        // 只由 sigZ 决定（无独立亮度项）⇒ 强边缘处跨边缘把伪彩抹平，亮度另走 sigY 路。
