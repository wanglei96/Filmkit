        // 50 = 镜头横向色差校正（v0.10.170）：0 = 关（A/B 通路，不跑任何 pass）；
        // >0 = 开关 + 估计位移的强度倍率。作用在 D3（RCD 去马赛克后 / CCM 前）
        // 相机 RGB 域，只重采样 R/B、G 不动；自动估计（1/8 降采样 + 径向 LK），
        // 角部位移 < 0.25px 判定无横向色差 ⇒ 整段跳过（零副作用）。
        // ⚠️ 默认 1.0 的实测依据与局限（对 2026-10-05 逆光基准样片**不动作**）
